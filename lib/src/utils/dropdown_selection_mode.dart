/// Selection mode for the dropdown
///
/// This enum defines the possible selection behaviors for the dropdown widget.
enum DropdownSelectionMode {
  /// Single item selection mode
  ///
  /// Only one item can be selected at a time. Similar to a traditional
  /// dropdown or radio button group.
  single,

  /// Multiple item selection mode
  ///
  /// Multiple items can be selected simultaneously. Similar to checkboxes.
  multiple,
}
